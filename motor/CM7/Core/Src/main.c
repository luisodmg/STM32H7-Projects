// Control de dirección (servo) - GIRO
// PIN: TIM13_CH1 (normalmente PA6 o PF8)
void Turning_SetAngle(int16_t angle)
{
  if (angle > 90) angle = 90;
  if (angle < -90) angle = -90;

  // Mapear ángulo a ancho de pulso (1000µs a 2000µs)
  uint16_t pulseWidth = 1500 + (angle * 500) / 90;
  __HAL_TIM_SET_COMPARE(&htim13, TIM_CHANNEL_1, pulseWidth);
}

// Control de velocidad ESC - ADELANTE/ATRÁS
// PIN: PA7 (TIM14_CH1)
// speed: -100 (máxima reversa) a +100 (máxima adelante), 0 = neutral
void setEscSpeed(int8_t speed)
{
    uint16_t pulseWidth;

    if (speed > 100) speed = 100;
    if (speed < -100) speed = -100;

    pulseWidth = 1500 + (speed * 5);

    if (pulseWidth < 1000) pulseWidth = 1000;
    if (pulseWidth > 2000) pulseWidth = 2000;

    __HAL_TIM_SET_COMPARE(&htim14, TIM_CHANNEL_1, pulseWidth);
}

// Detener motor (neutral) - PA7
void stopCarEsc(void)
{
    __HAL_TIM_SET_COMPARE(&htim14, TIM_CHANNEL_1, 1500);
}

// Función para movimiento suave adelante - PA7
void moveForward(uint8_t speed)
{
    if (speed > 100) speed = 100;
    setEscSpeed(speed);
}

// Función para movimiento suave atrás - PA7
void moveBackward(uint8_t speed)
{
    if (speed > 100) speed = 100;
    setEscSpeed(-speed);
}

// Función para giro suave - TIM13_CH1
void turn(int16_t angle)
{
    Turning_SetAngle(angle);
}

// Parada completa - Ambos pines
void stopCar(void)
{
    stopCarEsc();      // PA7 - Motor neutral
    Turning_SetAngle(0); // TIM13_CH1 - Dirección centrada
}

